#!/usr/bin/env python3
"""Generate tests/hpack_rfc_vectors.h from RFC 7541 Appendix C.

Usage: gen_vectors.py <rfc7541.txt>   (writes the header to stdout)

Every example the RFC gives for header field representation (C.2) and for
whole header lists (C.3 to C.6) becomes one entry: the encoded octets, the
header list, and the dynamic table after decoding. The unit tests then check
the decoder and the encoder against the RFC's own text and not against a
transcription made by hand. `make check-hpack-tables` fails if the committed
header is not what this produces from the pinned RFC.
"""
import re
import sys


def clean(text):
    """Drop page breaks (footer, blank lines, header) from the RFC text."""
    out = []
    for line in text.split("\n"):
        if re.match(r"^Peon & Ruellan\s+Standards Track\s+\[Page \d+\]", line):
            continue
        if re.match(r"^RFC 7541\s+HPACK\s+May 2015", line):
            continue
        out.append(line)
    return "\n".join(out)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path):
    text = clean(open(path, encoding="ascii").read())
    start = text.index("Appendix C.  Examples")
    text = text[start:]
    # Split at the example headings C.x.y.
    parts = re.split(r"^(C\.[2-6]\.\d+)\.  .*$", text, flags=re.M)
    examples = []
    for i in range(1, len(parts), 2):
        eid, body = parts[i], parts[i + 1]
        m = re.search(r"Hex dump of encoded data:\n(.*?)\n\n", body, re.S)
        if not m:
            sys.exit("%s: no hex dump" % eid)
        hexs = ""
        for ln in m.group(1).split("\n"):
            hexs += ln.split("|")[0].replace(" ", "")
        hdr = re.search(r"Header list to encode:\n\n(.*?)\n\n", body, re.S)
        if not hdr:
            sys.exit("%s: no header list" % eid)
        fields = []
        for ln in hdr.group(1).split("\n"):
            ln = ln.strip()
            name, _, value = ln.partition(": ")
            fields.append((name, value))
        table = []
        tsize = 0
        mt = re.search(r"Dynamic Table \(after decoding\):\n(.*?)\n\s*\n\s*Decoded header list:",
                       body, re.S)
        if mt:
            rows = []
            for ln in mt.group(1).split("\n"):
                ln = ln.strip()
                if not ln:
                    continue
                if ln.startswith("[") or ln.startswith("Table size"):
                    rows.append(ln)
                else:
                    rows[-1] += " " + ln  # a wrapped entry
            for ln in rows:
                mm = re.match(r"\[\s*(\d+)\] \(s =\s*(\d+)\) (\S+):(?: (.*))?$", ln)
                if mm:
                    table.append((mm.group(3), mm.group(4) or ""))
                    continue
                mm = re.match(r"Table size:\s*(\d+)", ln)
                if mm:
                    tsize = int(mm.group(1))
        examples.append((eid, hexs, fields, table, tsize))

    out = []
    w = out.append
    w("""// GENERATED by tools/hpack/gen_vectors.py from RFC 7541 Appendix C.
// Do not edit: `make check-hpack-tables` fails if this file is not what the
// generator produces from the pinned RFC text.
//
// Copyright 2026 by Corey Pennycuff

#ifndef GHOTI_IO_GHTTP_TEST_HPACK_RFC_VECTORS_H
#define GHOTI_IO_GHTTP_TEST_HPACK_RFC_VECTORS_H

#include <cstddef>
#include <utility>
#include <vector>

namespace ghttptest {

struct RfcExample {
  const char * id;                 // "C.3.2"
  const char * hex;                // the encoded octets
  std::vector<std::pair<const char *, const char *>> list;   // header list
  std::vector<std::pair<const char *, const char *>> table;  // after decoding, newest first
  size_t table_size;               // its size, RFC 7541 section 4.1
};

inline const std::vector<RfcExample> & rfc_examples() {
  static const std::vector<RfcExample> v = {""")
    for eid, hexs, fields, table, tsize in examples:
        w("    {%s, %s," % (cstr(eid), cstr(hexs)))
        w("     {" + ", ".join("{%s, %s}" % (cstr(n), cstr(v)) for n, v in fields) + "},")
        w("     {" + ", ".join("{%s, %s}" % (cstr(n), cstr(v)) for n, v in table) + "},")
        w("     %d}," % tsize)
    w("""  };
  return v;
}

} // namespace ghttptest

#endif // GHOTI_IO_GHTTP_TEST_HPACK_RFC_VECTORS_H""")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
